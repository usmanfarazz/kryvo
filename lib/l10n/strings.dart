/// App languages.
///
/// Text is written in English in the code and passed through [tr], which
/// returns the translation for the current language (or the English text if
/// there is none yet). The shared widgets (settings tiles, section headers,
/// dialogs, snack bars) already call [tr], so most screens are covered
/// without touching every string.
library;

class Lang {
  final String code;
  final String name; // in its own language
  final bool rtl;
  const Lang(this.code, this.name, {this.rtl = false});
}

const kLanguages = [
  Lang('en', 'English'),
  Lang('ur', 'اردو', rtl: true),
  Lang('hi', 'हिन्दी'),
  Lang('ar', 'العربية', rtl: true),
  Lang('bn', 'বাংলা'),
  Lang('tr', 'Türkçe'),
  Lang('id', 'Bahasa Indonesia'),
  Lang('es', 'Español'),
  Lang('fr', 'Français'),
  Lang('de', 'Deutsch'),
  Lang('pt', 'Português'),
  Lang('it', 'Italiano'),
  Lang('ru', 'Русский'),
  Lang('fa', 'فارسی', rtl: true),
  Lang('zh', '中文'),
  Lang('ja', '日本語'),
  Lang('ko', '한국어'),
  Lang('ms', 'Bahasa Melayu'),
];

String _current = 'en';
String get currentLang => _current;
void setCurrentLang(String code) =>
    _current = kLanguages.any((l) => l.code == code) ? code : 'en';

/// Translate [s] into the current language.
String tr(String s) => _current == 'en' ? s : (_t[_current]?[s] ?? s);

